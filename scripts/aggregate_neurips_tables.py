def alpha_dial_table() -> str:
    """Operator-controlled α sweep (all at λ=0.5, LLaVA-1.5-7B, visible)."""
    rows = [
        ("mmsafety_llava_cmc_alpha05", "α = 0.05"),
        ("mmsafety_llava_cmc_full",   "α = 0.10 (default)"),
        ("mmsafety_llava_cmc_alpha20","α = 0.20"),
    ]
    lines = ["# α-dial sweep (CMC, λ=0.5)\n",
             "| Setting | n | Defended unsafe | Attack flag | Clean flag | Δ unsafe (attack→defended) |",
             "|---|---|---|---|---|---|"]
    for name, label in rows:
        lines.append(_summary_row(name, label, baseline_unsafe=_VISIBLE_BASELINE_UNSAFE))
    return "\n".join(lines)


