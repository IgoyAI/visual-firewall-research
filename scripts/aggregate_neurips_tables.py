def mmbench_utility_table() -> str:
    """MMBench MCQ accuracy retention by defense (paper Table 9 utility column)."""
    rows = [
        ("mmbench_siglip_dev_subset", "Keyword (default)"),
        ("mmbench_subset_semantic",   "Semantic-only SigLIP"),
        ("mmbench_subset_cmc",        "CMC + conformal"),
    ]
    lines = ["# MMBench utility (defended_control vs base accuracy, n=32 samples)\n",
             "| Defense | base acc | def_control acc | retention | clean flag |",
             "|---|---|---|---|---|"]
    for name, label in rows:
        sp = RESULTS / name / "summary.json"
        if not sp.exists():
            lines.append(f"| {label} | **missing** | - | - | - |")
            continue
        s = json.loads(sp.read_text())
        v = s.get("variants", {})
        base = v.get("base", {}).get("judge_rate")
        dc = v.get("defended_control", {}).get("judge_rate")
        cf = v.get("defended_control", {}).get("firewall_flag_rate")
        ret = (dc / base) if (base and dc is not None) else None
        def fmt(x, d=3):
            return f"{x:.{d}f}" if isinstance(x, (int, float)) else "-"
        lines.append(f"| {label} | {fmt(base)} | {fmt(dc)} | {fmt(ret)} | {fmt(cf)} |")
    return "\n".join(lines)


def main() -> None:
    (OUT / "table_main.md").write_text(main_table() + "\n")
