    (OUT / "conformal_verification.md").write_text(conformal_verification() + "\n")
    (OUT / "alpha_dial.md").write_text(alpha_dial_table() + "\n")
    (OUT / "lambda_sweep.md").write_text(lambda_sweep_table() + "\n")
