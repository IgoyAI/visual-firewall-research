def target_models_table() -> str:
    """Cross-model target table (paper Table 8)."""
    rows = [
        ("mmsafety_llava_cmc_lambda003",  "LLaVA-1.5-7B"),
        ("mmsafety_qwen2vl_cmc_full",     "Qwen2-VL-7B"),
        ("mmsafety_qwen35_cmc_full",      "Qwen3.5-9B"),
        ("mmsafety_gemma4_cmc_full",      "Gemma 4 E4B-it"),
    ]
    lines = ["# Target-model results (paper Table 8)\n",
             "| Target MLLM | n | base | attacked | defended | atk_flag | clean_flag |",
             "|---|---|---|---|---|---|---|"]
    for name, label in rows:
        sp = RESULTS / name / "summary.json"
        if not sp.exists():
            lines.append(f"| {label} | - | **missing** | - | - | - | - |")
            continue
        s = json.loads(sp.read_text())
        v = s.get("variants", {})
        base = v.get("base", {}).get("unsafe_rate")
        atk  = v.get("attacked", {}).get("unsafe_rate")
        df   = v.get("defended_attack", {}).get("unsafe_rate")
        af   = v.get("defended_attack", {}).get("firewall_flag_rate")
        cf   = v.get("defended_control", {}).get("firewall_flag_rate")
        n    = v.get("defended_attack", {}).get("count")
        def fmt(x, d=3): return f"{x:.{d}f}" if isinstance(x, (int, float)) else "-"
        lines.append(f"| {label} | {n} | {fmt(base)} | {fmt(atk)} | {fmt(df)} | {fmt(af)} | {fmt(cf)} |")
    return "\n".join(lines)


